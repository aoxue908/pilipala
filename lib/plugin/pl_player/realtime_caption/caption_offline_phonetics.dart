/// 本地极速离线注音服务（0ms 同步秒出，彻底消除网络请求时延与丢字）
/// 专为中、日、韩、粤、英五大核心语言打造：
/// - 中文普通话：拼音 (Pinyin，带声调)
/// - 粤语：粤语拼音 (Jyutping，字词级精准标注)
/// - 日语：假名 (Hiragana) 与 罗马音 (Romaji)
/// - 韩语：韩语发音 (Revised Romanization 纯算法秒出)
/// - 英语：国际音标 (IPA，高频口语词汇与缩写秒出)
class CaptionOfflinePhonetics {
  static final _cantoneseParticles = RegExp(r'[佢咁唔喺哋咗嘅乜冇諗搵嘢㗎啫嘞嗰啱攰畀俾嚟咩啲噉啩]');

  /// Strong colloquial markers; ordinary shared words such as 食/玩 are not
  /// enough to override the language of a Chinese subtitle row.
  static bool hasCantoneseParticles(String text) => _cantoneseParticles.hasMatch(text);
  static final shared = CaptionOfflinePhonetics._();
  CaptionOfflinePhonetics._();

  /// 尝试进行本地离线注音转换 (0ms 同步完成，无网络请求)
  String? tryConvert(
    String text, {
    String japaneseMode = 'kana', // 'kana' 或 'romaji'
    String chineseMode = 'auto', // 'auto', 'cantonese', 'mandarin'
    bool isCantoneseContext = false,
    String? sourceLang,
  }) {
    try {
      final trimmed = text.trim();
      if (trimmed.isEmpty) return null;

    // 1. 日语识别 (语境明确为日语，或者未指定语境但包含日文平假名/片假名)
    final hasKana = RegExp(r'[぀-ゟ゠-ヿ]').hasMatch(trimmed);
    final isJa = sourceLang == 'ja' || (sourceLang == null && hasKana);
    if (isJa) {
      final ja = getJapanesePhonetic(trimmed, mode: japaneseMode);
      // 关键防错：语境明确为日语或包含假名时，即便句子全为汉字且离线未能覆盖，也绝不能跌落到普通话拼音！
      if (sourceLang == 'ja' || hasKana) return ja;
      if (ja != null && ja.isNotEmpty) return ja;
    }

    // 2. 韩语识别 (Unicode 纯数学算法，100%覆盖所有韩文音节)
    final isKo = sourceLang == 'ko' || (sourceLang == null && RegExp(r'[가-힯]').hasMatch(trimmed));
    if (isKo) {
      final ko = getKoreanRomaja(trimmed);
      if (sourceLang == 'ko') return ko;
      if (ko != null && ko.isNotEmpty) return ko;
    }

    // 3. 粤语 (Cantonese) 识别
    final isYue = sourceLang == 'yue' ||
        chineseMode == 'cantonese' ||
        isCantoneseContext ||
        (sourceLang == null && isCantoneseText(trimmed));
    if (isYue) {
      final yue = getCantoneseJyutping(trimmed);
      // 关键防错：既然语境或设置为粤语，就绝不能因为某些字词未覆盖而跌落成普通话拼音！
      if (yue != null && yue.isNotEmpty) return yue;
      if (sourceLang == 'yue' || chineseMode == 'cantonese' || isCantoneseContext || isCantoneseText(trimmed)) {
        return null;
      }
    }

    // 4. 如果语境明确为非中文（如英语 en、土耳其语 tr 等），绝不走中文拼音
    if (sourceLang != null && sourceLang != 'zh-CN' && sourceLang != 'zh') {
      if (sourceLang == 'en' || RegExp(r"^[a-zA-Z0-9\s\p{P}'\-]+$", unicode: true).hasMatch(trimmed)) {
        return getEnglishIpa(trimmed);
      }
      return null;
    }

    // 5. 中文普通话 (Mandarin) 拼音识别 (仅在确属中文语境且非粤语时)
    final hasChinese = RegExp(r'[一-鿿]').hasMatch(trimmed);
    if (hasChinese && chineseMode != 'cantonese') {
      final pinyinResult = getMandarinPinyin(trimmed);
      if (pinyinResult != null && pinyinResult.isNotEmpty) return pinyinResult;
    }

    // 6. 纯英语 / 拉丁字符音标 (IPA)
    if (RegExp(r"^[a-zA-Z0-9\s\p{P}'\-]+$", unicode: true).hasMatch(trimmed)) {
      return getEnglishIpa(trimmed);
    }

    return null;
    } catch (_) {
      return null;
    }
  }

  // ==========================================
  // 1. 韩语 (Korean) 纯算法 Revised Romanization
  // ==========================================
  static const _cho = [
    'g', 'kk', 'n', 'd', 'tt', 'r', 'm', 'b', 'pp', 's', 'ss', '',
    'j', 'jj', 'ch', 'k', 't', 'p', 'h'
  ];
  static const _jung = [
    'a', 'ae', 'ya', 'yae', 'eo', 'e', 'yeo', 'ye', 'o', 'wa', 'wae',
    'oe', 'yo', 'u', 'wo', 'we', 'wi', 'yu', 'eu', 'ui', 'i'
  ];
  static const _jong = [
    '', 'k', 'k', 'ks', 'n', 'nj', 'nh', 't', 'l', 'lg', 'lm', 'lb',
    'ls', 'lt', 'lp', 'lh', 'm', 'p', 'ps', 't', 't', 'ng', 't', 't',
    'k', 't', 'p', 'h'
  ];

  /// 韩文文本转罗马音 (Revised Romanization)，0ms 纯数学计算
  static String? getKoreanRomaja(String text) {
    final syllables = <String>[];
    for (final char in text.runes) {
      if (char >= 0xAC00 && char <= 0xD7A3) {
        final sylIndex = char - 0xAC00;
        final jong = sylIndex % 28;
        final jung = ((sylIndex - jong) ~/ 28) % 21;
        final cho = ((sylIndex - jong) ~/ 28) ~/ 21;
        syllables.add('${_cho[cho]}${_jung[jung]}${_jong[jong]}');
      } else {
        final s = String.fromCharCode(char).trim();
        if (s.isNotEmpty && !RegExp(r'''[\s.,!?:;，。！？；：、~·"'\(\)\[\]]''').hasMatch(s)) {
          syllables.add(s);
        }
      }
    }
    if (syllables.isEmpty) return null;
    return syllables.join(' ');
  }

  // ==========================================
  // 2. 日语 (Japanese) 假名算法与高频汉字词汇
  // ==========================================
  static String? getJapanesePhonetic(String text, {String mode = 'kana'}) {
    final tokens = JapaneseReadingService.shared.cached(text);
    final han = RegExp(r'\p{Script=Han}', unicode: true);
    if (tokens == null) {
      if (han.hasMatch(text)) return null;
      return mode == 'romaji' ? kanaToRomaji(text) : JapaneseReadingService.toHiragana(text);
    }
    final output = StringBuffer();
    for (final token in tokens) {
      if (token.reading.isEmpty && han.hasMatch(token.text)) return null;
      output.write(token.reading.isNotEmpty ? token.reading : token.text);
    }
    final kana = output.toString();
    return mode == 'romaji' ? kanaToRomaji(kana) : kana;
  }

  /// 假名转换为罗马音（同时支持平假名与片假名）
  static String? kanaToRomaji(String text) {
    // 过滤掉任何汉字，绝不向罗马音输出汉字
    final noHan = text.replaceAll(RegExp(r'[\u4E00-\u9FFF]'), ' ').trim();
    if (noHan.isEmpty) return null;

    // 仅在输出罗马音模式时，将片假名映射为平假名以便查找罗马音表
    final sb = StringBuffer();
    for (final code in noHan.runes) {
      if (code >= 0x30A1 && code <= 0x30F6) {
        sb.writeCharCode(code - 0x60);
      } else {
        sb.writeCharCode(code);
      }
    }
    var hira = sb.toString();
    hira = hira
        .replaceAll('こんにちは', ' konnichiwa ')
        .replaceAll('こんばんは', ' konbanwa ');
    return hiraganaToRomaji(hira);
  }

  /// 平假名转换为罗马音 (词组连贯输出，绝不生硬逐音节空格拆裂，标点自然对齐)
  static String? hiraganaToRomaji(String text) {
    if (RegExp(r'[\u4E00-\u9FFF]').hasMatch(text)) {
      return null;
    }

    const punctMap = {
      '，': ', ',
      ',': ', ',
      '、': ', ',
      '。': '. ',
      '.': '. ',
      '！': '! ',
      '!': '! ',
      '？': '? ',
      '?': '? ',
      ' ': ' ',
      '　': ' ',
      '~': '~',
      '～': '~',
      '…': '... ',
      '：': ': ',
      ':': ': ',
    };

    final parts = <String>[];
    var i = 0;
    while (i < text.length) {
      final ch = text[i];
      if (punctMap.containsKey(ch)) {
        parts.add(punctMap[ch]!);
        i++;
        continue;
      }
      // 促音 っ 处理 (如 まった -> matta, まって -> matte)
      if (ch == 'っ' && i + 1 < text.length) {
        final nextSub = i + 2 <= text.length ? text.substring(i + 1, i + 2) : '';
        if (_kanaToRomaji.containsKey(nextSub)) {
          final romaji = _kanaToRomaji[nextSub]!;
          if (romaji.isNotEmpty) {
            parts.add(romaji[0]);
          }
        }
        i++;
        continue;
      }
      // 双字符复合拗音 (如 きゃ, しゅ, ちょ)
      if (i + 2 <= text.length) {
        final sub2 = text.substring(i, i + 2);
        if (_kanaToRomaji.containsKey(sub2)) {
          parts.add(_kanaToRomaji[sub2]!);
          i += 2;
          continue;
        }
      }
      // 单字符假名
      final sub1 = text.substring(i, i + 1);
      if (_kanaToRomaji.containsKey(sub1)) {
        parts.add(_kanaToRomaji[sub1]!);
      } else if (!RegExp(r'''[\s.,!?:;，。！？；：、~·"'\(\)\[\]]''').hasMatch(sub1)) {
        if (RegExp(r'[\u4E00-\u9FFF]').hasMatch(sub1)) {
          return null; // 绝对不允许日式汉字流出到罗马音
        }
        parts.add(sub1);
      }
      i++;
    }

    final raw = parts.join('');
    final result = raw
        .replaceAllMapped(RegExp(r'\s+([,.:;?!])'), (m) => m[1]!)
        .replaceAll(RegExp(r' +'), ' ')
        .trim();

    if (result.isEmpty || RegExp(r'[\u4E00-\u9FFF]').hasMatch(result)) {
      return null;
    }
    return result;
  }

  // ==========================================
  // 3. 粤语 (Cantonese) Jyutping 离线解析
  // ==========================================
  /// Keep source offsets, including unmapped characters. Joining only known
  /// syllables loses the holes and shifts all subsequent annotations left.
  static Map<int, String> alignedChineseReadings(String text,
      {required bool cantonese}) {
    final readings = <int, String>{};
    var offset = 0;
    while (offset < text.length) {
      var phraseLength = 0;
      if (cantonese) {
        final phrase = CantoneseLexicon.shared.phraseAt(text, offset);
        if (phrase != null) {
          var index = 0;
          for (final rune in phrase.text.runes) {
            readings[offset] = phrase.syllables[index++];
            offset += String.fromCharCode(rune).length;
          }
          continue;
        }
        for (var length = math.min(4, text.length - offset); length >= 2; length--) {
          final phrase = _cantonesePhrases[text.substring(offset, offset + length)];
          if (phrase == null) continue;
          final syllables = phrase.split(' ');
          if (syllables.length != length) continue;
          for (var i = 0; i < length; i++) {
            readings[offset + i] = syllables[i];
          }
          phraseLength = length;
          break;
        }
      }
      if (phraseLength > 0) {
        offset += phraseLength;
        continue;
      }
      final char = String.fromCharCode(text.substring(offset).runes.first);
      final variants = cantonese ? CantoneseLexicon.shared.readings(char) : const <String>[];
      final reading = variants.isNotEmpty ? variants.first
          : (cantonese ? _cantoneseChars : _mandarinChars)[char];
      if (reading != null) readings[offset] = reading;
      offset += char.length;
    }
    return readings;
  }

  static String? getCantoneseJyutping(String text) {
    final clean = text.trim();
    if (clean.isEmpty) return null;
    final syllables = <String>[];
    var matchedCount = 0;
    var totalChinese = 0;

    final readings = alignedChineseReadings(clean, cantonese: true);
    final han = RegExp(r'\p{Script=Han}', unicode: true);
    var offset = 0;
    for (final rune in clean.runes) {
      final char = String.fromCharCode(rune);
      if (han.hasMatch(char)) {
        totalChinese++;
        final reading = readings[offset];
        if (reading != null) {
          syllables.add(reading);
          matchedCount++;
        }
      } else if (RegExp(r'[a-zA-Z0-9]').hasMatch(char)) {
        syllables.add(char);
      }
      offset += char.length;
    }

    // 关键优化：只要有汉字被成功匹配（且匹配率达到 40% 以上），就立即返回 0ms 离线结果！
    // 绝不轻易返回 null，彻底杜绝因为个别生僻字导致掉入 429 崩溃风暴或被误判成普通话！
    if (totalChinese > 0 && matchedCount >= (totalChinese * 0.4).ceil()) {
      return syllables.join(' ');
    }
    return null;
  }

  // ==========================================
  // 4. 中文普通话 (Mandarin) 拼音离线解析
  // ==========================================
  static String? getMandarinPinyin(String text) {
    final clean = text.trim();
    if (clean.isEmpty) return null;
    final syllables = <String>[];
    var matchedCount = 0;
    var totalChinese = 0;

    for (var i = 0; i < clean.length; i++) {
      final c = clean[i];
      if (RegExp(r'[一-鿿]').hasMatch(c)) {
        totalChinese++;
        if (_mandarinChars.containsKey(c)) {
          syllables.add(_mandarinChars[c]!);
          matchedCount++;
        }
      } else if (RegExp(r'[a-zA-Z0-9]').hasMatch(c)) {
        syllables.add(c);
      }
    }

    if (totalChinese > 0 && matchedCount >= totalChinese * 0.6) {
      return syllables.join(' ');
    }
    return null;
  }

  // ==========================================
  // 5. 英语 (English) 国际音标 (IPA) 离线解析
  // ==========================================
  static String? getEnglishIpa(String text) {
    final clean = text.trim();
    if (clean.isEmpty) return null;
    final words = clean.split(RegExp(r'(\s+|[.,!?;:"])')).where((w) => w.isNotEmpty).toList();
    if (words.isEmpty) return null;

    final ipaParts = <String>[];
    var matchedCount = 0;

    for (final word in words) {
      final lower = word.toLowerCase().replaceAll(RegExp(r"[^a-z']"), '');
      if (lower.isEmpty) continue;

      if (_englishIpaDict.containsKey(lower)) {
        ipaParts.add(_englishIpaDict[lower]!);
        matchedCount++;
      } else {
        ipaParts.add(lower);
      }
    }

    if (ipaParts.isNotEmpty && matchedCount > 0) {
      return ipaParts.join(' ');
    }
    return null;
  }

  /// 识别是否包含粤语特征字词与语法句式
  static bool isCantoneseText(String text) {
    final trimmed = text.trim();
    if (trimmed.isEmpty) return false;

    const cantoneseChars =
        '唔喺哋咗嘅乜冇睇諗搵嘢㗎啫嘞咁係咪佢瞓返落講食玩靚靓咧呐呢嗰啱卒攰慳撩嘈噏嗌喐掟氹掹抌拗黐抦扯畀俾冧嘥埗邨鎅揸攞踎';
    for (var i = 0; i < trimmed.length; i++) {
      if (cantoneseChars.contains(trimmed[i])) return true;
    }
    if (RegExp(r'(先[。？！?!~…\s]*$|先啦|先至|先係|先系|先讲|先食|先走|钱先)').hasMatch(trimmed)) {
      return true;
    }
    for (final phrase in _cantonesePhrases.keys) {
      if (trimmed.contains(phrase)) return true;
    }
    return false;
  }

